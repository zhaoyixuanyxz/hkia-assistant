def test_us7_pitch_unchanged_in_prd() -> None:
    text = _PRD.read_text(encoding="utf-8")
    assert _PITCH in text


def test_us7_standard_disclaimers_unchanged() -> None:
    for loc, expected in _EXPECTED_DISCLAIMERS.items():
        assert STANDARD_DISCLAIMERS[loc] == expected


def test_us7_allowed_product_url_china_life_only() -> None:
    assert allowed_product_url(
        "https://www.chinalife.com.hk/zh-hk/products/insurance/medical/example-plan"
    )
    assert not allowed_product_url("https://example.com/zh-hk/products/insurance/medical/x")
    assert not allowed_product_url("https://www.chinalife.com.hk/zh-hk/about")
    assert not allowed_product_url(
        "https://www.chinalife.com.hk/zh-hk/products/insurance"
    )


