def _build_disclaimer_suffixes_strip() -> tuple[str, ...]:
    parts: list[str] = []
    parts.extend(STANDARD_DISCLAIMERS.values())
    parts.extend(SHORT_DISCLAIMERS.values())
    parts.extend(_LEGACY_DISCLAIMER_SUFFIXES)
    # Longest first so shorter suffixes do not leave leftover footer fragments
    return tuple(sorted(set(parts), key=len, reverse=True))


# Longest first: strip trailing footers to detect empty substantive body
_DISCLAIMER_SUFFIXES_STRIP: tuple[str, ...] = _build_disclaimer_suffixes_strip()


def disclaimer_for(locale: str | None) -> str:
    return STANDARD_DISCLAIMERS[normalize_locale(locale)]


def short_disclaimer_for(locale: str | None) -> str:
    return SHORT_DISCLAIMERS[normalize_locale(locale)]


def empty_body_fallback_for(locale: str | None) -> str:
    return EMPTY_BODY_FALLBACKS[normalize_locale(locale)]


def second_fallback_for(locale: str | None) -> str:
    return SECOND_FALLBACKS[normalize_locale(locale)]


def failure_reply_for(locale: str | None) -> str:
    loc = normalize_locale(locale)
    return ensure_disclaimer_text(FAILURE_BASES[loc], locale=loc)


def _strip_trailing_disclaimer_blocks(text: str) -> str:
    t = text.strip()
    changed = True
    while changed and t:
        changed = False
        for suffix in _DISCLAIMER_SUFFIXES_STRIP:
            if t.endswith(suffix):
                t = t[: -len(suffix)].rstrip()
                if t.endswith("\n\n"):
                    t = t[:-2].rstrip()
                changed = True
                break
    return t.strip()


def _body_has_substantive_tokens(body: str) -> bool:
    """True if visible text has at least one Unicode letter or number.

    The old ASCII+CJK-BMP-only regex misclassified rare ideographs, fullwidth
    digits-only snippets, and some scripts as 'empty', triggering the canned
    fallback that looks like forgotten context.
    """
    s = body.strip()
    if not s:
        return False
    for ch in s:
        if ch.isspace():
            continue
        cat = unicodedata.category(ch)
        if cat.startswith("L") or cat.startswith("N"):
            return True
    return False


def _join_body_and_suffix(body: str, suffix: str) -> str:
    b = body.rstrip()
    su = (suffix or "").strip()
    if not b:
        return su
    if not su:
        return b
    if b[-1] in "。！？…」』.!?:;":
        return f"{b}{su}"
    return f"{b}。{su}"

def _body_len_bounds(
    min_len: int | None,
    max_len: int | None,
) -> tuple[int, int]:
    if min_len is not None and max_len is not None:
        return min_len, max_len
    s = get_settings()
    return s.chat_body_len_min, s.chat_body_len_max


def enforce_chat_body_length_range(
    body: str,
    min_len: int | None = None,
    max_len: int | None = None,
    *,
    locale: str | None = None,
) -> str:
    """Clamp assistant-visible body to [min_len, max_len] characters (Python len)."""
    lo, hi = _body_len_bounds(min_len, max_len)
    loc = normalize_locale(locale)
    pad_suffixes = _LENGTH_PAD_SUFFIXES_BY_LOCALE.get(loc, _LENGTH_PAD_SUFFIXES)
    s = (body or "").strip()
    if len(s) > hi:
        s = s[:hi]
    if lo <= len(s) <= hi:
        return s
    for suf in pad_suffixes:
        cand = _join_body_and_suffix(s, suf)
        if lo <= len(cand) <= hi:
            return cand
    best = ""
    for suf in pad_suffixes:
        cand = _join_body_and_suffix(s, suf)
        if len(cand) > hi:
            continue
        if len(cand) >= lo:
            return cand
        if len(cand) > len(best):
            best = cand
    if loc == "en":
        frag = (
            " To better match your situation, please also share one coverage gap or budget range "
            "you care about most; mention voluntary medical or company group cover if you have it."
        )
    elif loc == "zh-TW":
        frag = (
            "為更準確匹配你的情況，也請補充一項最關心的保障缺口或預算區間；"
            "若已有自願醫保或公司團險也可一併說明。"
        )
    else:
        frag = (
            "为更准确匹配你的情况，也请补充一项最关心的保障缺口或预算区间；"
            "若已有自愿医保或公司团险也可一并说明。"
        )
    while len(s) < lo:
        cand = _join_body_and_suffix(s, frag)
        if len(cand) <= hi:
            s = cand
        else:
            if len(s) < hi:
                s = (s + frag)[:hi]
            break
    if len(s) >= lo:
        return s
    if len(best) >= lo:
        return best
    return enforce_chat_body_length_range(
        empty_body_fallback_for(loc).strip(),
        min_len=lo,
        max_len=hi,
        locale=loc,
    )


def assistant_content_for_llm(stored_assistant_message: str) -> str:
    """Strip persisted compliance footers so the model sees only the user-facing reply body."""
    stripped = _strip_trailing_disclaimer_blocks(stored_assistant_message or "")
    if stripped:
        return stripped
    s = (stored_assistant_message or "").strip()
    return s if s else "(上一轮助手正文缺失)"


def chat_reply_has_substantive_body(text: str | None) -> bool:
    """True if message has visible content beyond known compliance footers."""
    return _body_has_substantive_tokens(_strip_trailing_disclaimer_blocks(text or ""))


def normalize_chat_assistant_body(raw: str | None, *, locale: str | None = None) -> str:
    """Strip trailing disclaimer blocks; apply empty-body fallbacks. Does not enforce length."""
    loc = normalize_locale(locale)
    body = _strip_trailing_disclaimer_blocks((raw or "").strip())
    if not _body_has_substantive_tokens(body):
        logger.warning("chat_assistant_empty_body_fallback applied")
        body = empty_body_fallback_for(loc)
    if not _body_has_substantive_tokens(body):
        logger.error("chat_assistant_empty_body_fallback_invalid")
        body = second_fallback_for(loc)
    return body.strip()


def finalize_chat_assistant_text(raw: str | None, *, locale: str | None = None) -> str:
    """Router / persistence guard: ensure disclaimer and length in case graph skipped steps."""
    loc = normalize_locale(locale)
    lo, hi = _body_len_bounds(None, None)
    body = normalize_chat_assistant_body(raw, locale=loc)
    if not (lo <= len(body) <= hi):
        body = enforce_chat_body_length_range(body, min_len=lo, max_len=hi, locale=loc)
    return ensure_disclaimer_text(body, locale=loc)


def ensure_disclaimer_text(text: str | None, *, locale: str | None = None) -> str:
    """Ensure the standard footer appears exactly once (suffix match)."""
    disc = disclaimer_for(locale)
    base = (text or "").strip()
    if not base:
        return disc
    if base.endswith(disc):
        return base
    return f"{base}\n\n{disc}"


def merge_report_disclaimer(body_disclaimer: str | None, *, locale: str | None = None) -> str:
    loc = normalize_locale(locale)
    return ensure_disclaimer_text(body_disclaimer or disclaimer_for(loc), locale=loc)


def assistant_pipeline_failure_reply(locale: str | None = None) -> str:
    return failure_reply_for(locale)
